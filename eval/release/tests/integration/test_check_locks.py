"""The check of the gate image that the two locks agree on every package they share.

eval/release/gate/check_locks.py runs in the build of the gate image, between the install from
ai-service/uv.lock and the install from eval/release/uv.lock (eval/release/gate/Dockerfile).
Here it runs as the build runs it: a separate Python process on two text files.
"""

import subprocess
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[2] / "gate" / "check_locks.py"
# `uv pip freeze` of the environment that ai-service/uv.lock installed: a name that is not in
# normalized form, and the path install of ai-service, which has no pin.
INSTALLED = "anyio==4.12.0\nHttpx==0.28.1\nsupportiq-ai-service @ file:///build/ai-service\n"


def exported(httpx_version: str) -> str:
    """Return a `uv export` of eval/release/uv.lock that pins httpx at `httpx_version`."""
    hash_line = "    --hash=sha256:" + "0" * 64
    return "\n".join(
        [
            "# This file was autogenerated by uv via the following command:",
            "anyio==4.12.0 \\",
            hash_line,
            "    # via httpx",
            "colorama==0.4.6 ; sys_platform == 'win32' \\",
            hash_line,
            f"httpx=={httpx_version} \\",
            hash_line,
            "",
        ]
    )


def check_locks(tmp_path: Path, httpx_version: str) -> subprocess.CompletedProcess[str]:
    """Run the check on the freeze above and an export with the given version of httpx."""
    installed = tmp_path / "installed.txt"
    installed.write_text(INSTALLED, encoding="utf-8")
    requirements = tmp_path / "requirements.txt"
    requirements.write_text(exported(httpx_version), encoding="utf-8")
    return subprocess.run(  # noqa: S603  # the interpreter of this run on files of this test
        [sys.executable, "-I", str(SCRIPT), str(installed), str(requirements)],
        capture_output=True,
        text=True,
        check=False,
    )


def test_locks_that_pin_a_shared_package_at_two_versions_stop_the_build(tmp_path: Path) -> None:
    result = check_locks(tmp_path, "0.28.2")

    assert result.returncode == 1
    assert result.stderr == (
        "the locks disagree on httpx: ai-service/uv.lock 0.28.1, eval/release/uv.lock 0.28.2\n"
    )


def test_locks_that_agree_on_every_shared_package_pass(tmp_path: Path) -> None:
    result = check_locks(tmp_path, "0.28.1")

    assert result.returncode == 0
    assert result.stderr == ""
